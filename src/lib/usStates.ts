export type UsStateCode = (typeof US_STATE_OPTIONS)[number]['code'];

const STATE_NAME_BY_CODE = new Map<string, string>(
  US_STATE_OPTIONS.map((state) => [state.code, state.name]),
);

const STATE_CODE_BY_NAME = new Map<string, UsStateCode>(
  US_STATE_OPTIONS.map((state) => [state.name.toLowerCase(), state.code]),
);

/** Normalize "ny", "New York", or "N.Y." to `NY`. */
export function normalizeUsState(value: unknown): UsStateCode | '' {
  if (typeof value !== 'string') return '';
  const trimmed = value.trim();
  if (!trimmed) return '';
  const compact = trimmed.replace(/[.\s]/g, '');
  const upper = compact.toUpperCase();
  if (STATE_NAME_BY_CODE.has(upper)) return upper as UsStateCode;
  return STATE_CODE_BY_NAME.get(trimmed.toLowerCase()) ?? '';
}

export function usStateName(code: string | null | undefined): string {
  const normalized = normalizeUsState(code);
  return normalized ? STATE_NAME_BY_CODE.get(normalized) || normalized : '';
}
